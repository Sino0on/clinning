// Админка всегда светлая (UNFOLD["THEME"] = "light"), но Unfold 0.91 берёт
// тему из localStorage браузера. Если устройство заходило в админку раньше,
// там остаётся "auto", и при тёмном режиме телефона админка становилась
// тёмной, не как на скриншотах в инструкции. Скрипт подключается до Alpine.
try {
  localStorage.setItem('adminTheme', '"light"');
} catch (e) {
  // Приватный режим или запрет хранилища: тогда Unfold и так возьмёт светлую
}
