class Command(BaseCommand):
    help = "Создаёт страницу-образец «Уборка после стройки», если её ещё нет"

    @transaction.atomic
    def handle(self, *args, **options):
        if ServicePage.objects.filter(slug=SLUG).exists():
            self.stdout.write(f"Страница /uslugi/{SLUG} уже есть, ничего не меняю.")
            return
        page = ServicePage(**PAGE)
        # Карточка «Послестроительная» на главной получит кнопку «Подробнее»
        # (сравнение в Python: SQLite не умеет icontains для кириллицы)
        card = next(
            (s for s in Service.objects.filter(page__isnull=True) if "послестро" in s.title_ru.lower()),
            None,
        )
        if card:
            page.service = card
        page.save()
        for i, (q_ru, a_ru, q_ky, a_ky) in enumerate(FAQ):
            ServicePageFAQ.objects.create(
                page=page, position=i, question_ru=q_ru, answer_ru=a_ru, question_ky=q_ky, answer_ky=a_ky
            )
        linked = f", связана с карточкой «{card.title_ru}»" if card else ""
        self.stdout.write(f"Создана страница /uslugi/{SLUG}{linked}.")
